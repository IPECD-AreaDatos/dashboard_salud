export function classesForStyle(style: CSSProperties | null | undefined | false): string {
  if (!style) return "";
  const classes: string[] = [];
  for (const [property, value] of Object.entries(style)) {
    if (value === undefined || value === null || typeof value === "boolean" || value === "") continue;
    if (typeof value === "string" && ["width", "height", "left"].includes(property)) {
      const percentage = /^(-?\d+(?:\.\d+)?)%$/.exec(value);
      if (percentage) {
        const size = Math.max(0, Math.min(100, Math.round(Number(percentage[1]))));
        classes.push(styles[`dim_${property}_${size}` as keyof typeof styles]);
        continue;
      }
    }
    if (property === "height" && typeof value === "string") {
      const pixels = /^(\d+(?:\.\d+)?)px$/.exec(value);
      if (pixels) {
        const size = Math.max(0, Math.min(800, Math.round(Number(pixels[1]))));
        classes.push(styles[`dim_height_px_${size}` as keyof typeof styles]);
        continue;
      }
    }
    const className = styleClasses[`${property}\u0000${String(value)}`];
    if (className) classes.push(className);
  }
  return classes.filter(Boolean).join(" ");
}

export function mergeClassNames(...values: Array<string | false | null | undefined>): string {
  return values.filter((value): value is string => typeof value === "string" && value.length > 0).join(" ");
}
